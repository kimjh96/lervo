import {
  assertCompleteEffectInventory,
  type EffectBoundaryCategory,
  type EffectBoundaryContract,
  type EffectKind,
} from "@lervo/execution-contract";

interface EffectDeclaration {
  effectId: string;
  category: EffectBoundaryCategory;
  owner: string;
  effectKind: EffectKind;
  idempotencyCoordinate: string;
  duplicateBehavior: EffectBoundaryContract["duplicateBehavior"];
  automaticRetry: EffectBoundaryContract["automaticRetry"];
  uncertainty: EffectBoundaryContract["uncertainty"];
  compensation: EffectBoundaryContract["compensation"];
  durableSuccessEvidence: string;
  recoveryOwner: string;
  privacySafeFailureCode: string;
  growingCollectionIds: string[];
}

function declareEffect(value: EffectDeclaration): EffectBoundaryContract {
  const external = value.effectKind === "external";
  return {
    schemaVersion: 1,
    ...value,
    cancellation: {
      beforeStart: "cancelled_without_effect",
      duringEffect: external ? "reconcile_required" : "rollback_or_recovery_required",
      afterEffect: "complete_or_recovery_required",
    },
    absenceMeaning: "not_completed_or_unobserved",
  };
}

