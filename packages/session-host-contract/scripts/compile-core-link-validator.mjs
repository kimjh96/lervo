// Compiles the core-link request schema into a standalone validator at build time, so the
// resident Lervo process validates requests without loading Ajv's compiler (and its URI and
// traversal dependencies) at runtime. The repository's schema validators follow the same rule.
import { Ajv2020 } from "ajv/dist/2020.js";
import standaloneCode from "ajv/dist/standalone/index.js";
import { build } from "esbuild";
import { resolve } from "node:path";

/**
 * The validator module's source for the core-link `document`: one export,
 * `validateCoreLinkRequest`, with no imports.
 */
export async function compileCoreLinkValidator(document) {
  const ajv = new Ajv2020({
    strict: true,
    allErrors: false,
    code: { source: true, esm: true, optimize: 2 },
  });
  ajv.addSchema(document);
  const source = standaloneCode(ajv, {
    validateCoreLinkRequest: `${document.$id}#/$defs/CoreLinkRequest`,
  });
  const bundled = await build({
    stdin: { contents: source, resolveDir: import.meta.dirname, sourcefile: "validator.js" },
    // Paths in the output are relative to this directory, so it is the same everywhere.
    absWorkingDir: resolve(import.meta.dirname, ".."),
    bundle: true,
    write: false,
    format: "esm",
    platform: "neutral",
    target: "es2022",
    legalComments: "none",
    minify: true,
    logLevel: "silent",
  });
  const code = Buffer.from(bundled.outputFiles[0].contents).toString("utf8");
  return `// Generated by scripts/compile-core-link-validator.mjs from the core-link document. Do not edit.\n${code}`;
}
