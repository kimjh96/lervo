import { mkdir, mkdtemp, readFile, rm, writeFile } from "node:fs/promises";
import { tmpdir } from "node:os";
import { resolve } from "node:path";
import { afterEach, expect, it } from "vitest";
import { applyInitPlan, createInitPlan } from "@lervo/project";
import {
  applyTerminalIntegrationPlan,
  createTerminalIntegrationPlan,
  inspectTerminalIntegration,
  verifyTerminalHookRuntimeArtifact,
  serializableTerminalIntegrationPlan,
  recoverKnowledgeMaterialization,
  sha256,
  type TerminalRuntimeAsset,
  type KnowledgeMaterializationCheckpoint,
} from "../src/index.js";
import { terminalRuntimeManifest } from "../src/terminal-runtime-manifest.js";

const roots: string[] = [];
const launcher = "#!/usr/bin/env node\nprocess.exit(0);\n";
const legacyRuntime = `#!/usr/bin/env node\n//${"x".repeat(20 * 1024)}\n`;
function assets(schema: number): TerminalRuntimeAsset[] {
  const names: Array<"file-sync" | "cas-io"> =
    schema === 1 ? [] : schema === 2 ? ["file-sync"] : ["cas-io", "file-sync"];
  return names.flatMap((name) => {
    const content = Buffer.from([0, 255, 128, name.length, 0, 254]);
    return [
      { path: `native/${name}-darwin.node`, content },
      {
        path: `native/${name}.json`,
        content: Buffer.from(
          JSON.stringify({
            schemaVersion: 1,
            apiVersion: 1,
            napiVersion: 8,
            platform: "darwin",
            architectures: ["arm64", "x64"],
            sourceHash: sha256("source"),
            contentHash: sha256(content),
          }),
        ),
      },
    ] as TerminalRuntimeAsset[];
  });
}
async function legacy(schema = 3) {
  const root = await mkdtemp(resolve(tmpdir(), "lervo-terminal-migration-"));
  roots.push(root);
  await applyInitPlan(
    await createInitPlan({
      root,
      projectId: "prj_terminal_native",
      now: new Date("2026-10-10T00:00:00Z"),
    }),
  );
  const initial = await createTerminalIntegrationPlan(root, launcher);
  await applyTerminalIntegrationPlan({
    plan: initial,
    runtimeContent: launcher,
    now: new Date(),
    recordApplied: () => undefined,
  });
  const directory = resolve(root, ".lervo/generated/terminal-hooks");
  await writeFile(resolve(directory, "runtime-v2.mjs"), legacyRuntime);
  await writeFile(
    resolve(directory, "runtime-v2.json"),
    terminalRuntimeManifest(legacyRuntime, assets(schema), schema),
  );
  for (const asset of assets(schema)) {
    await mkdir(resolve(directory, "native"), { recursive: true });
    await writeFile(resolve(directory, asset.path), asset.content);
  }
  return { root, directory };
}
afterEach(async () => {
  await Promise.all(roots.splice(0).map((root) => rm(root, { recursive: true, force: true })));
});

it.each([1, 2, 3])(
  "reads schema %s and migrates only generated bytes to schema 4",
  async (schema) => {
    const { root, directory } = await legacy(schema);
    expect(await verifyTerminalHookRuntimeArtifact(resolve(directory, "runtime-v2.mjs"))).toBe(
      true,
    );
    const providers = await Promise.all(
      [".codex/hooks.json", ".claude/settings.json"].map((path) => readFile(resolve(root, path))),
    );
    const plan = await createTerminalIntegrationPlan(root, launcher);
    expect(plan.status).toBe("ready");
    expect(plan.approvalHash).toBeNull();
    expect(JSON.stringify(serializableTerminalIntegrationPlan(plan))).not.toContain('"content":');
    expect(plan.operations.filter((operation) => operation.action === "delete")).toHaveLength(
      assets(schema).length,
    );
    let runtimeAfterHash: string | null = null;
    await applyTerminalIntegrationPlan({
      plan,
      runtimeContent: launcher,
      now: new Date(),
      recordApplied: (receipt) => {
        runtimeAfterHash = receipt.runtimeAfterHash;
      },
    });
    expect(runtimeAfterHash).toBe(sha256(launcher));
    expect(await readFile(resolve(directory, "runtime-v2.mjs"), "utf8")).toBe(launcher);
    expect(JSON.parse(await readFile(resolve(directory, "runtime-v2.json"), "utf8"))).toMatchObject(
      { schemaVersion: 4, kind: "lervo_terminal_hook_launcher" },
    );
    await expect(readFile(resolve(directory, "native/cas-io-darwin.node"))).rejects.toMatchObject({
      code: "ENOENT",
    });
    await expect(
      readFile(resolve(directory, "native/file-sync-darwin.node")),
    ).rejects.toMatchObject({ code: "ENOENT" });
    expect(
      await Promise.all(
        [".codex/hooks.json", ".claude/settings.json"].map((path) => readFile(resolve(root, path))),
      ),
    ).toEqual(providers);
    expect((await inspectTerminalIntegration(root)).status).toBe("current");
    expect((await createTerminalIntegrationPlan(root, launcher)).status).toBe("current");
  },
);
it.each(["original_moved:0", "published:4"] as KnowledgeMaterializationCheckpoint[])(
  "restores the legacy runtime and binary assets on failure at %s",
  async (checkpoint) => {
    const { root, directory } = await legacy();
    const plan = await createTerminalIntegrationPlan(root, launcher);
    await expect(
      applyTerminalIntegrationPlan({
        plan,
        runtimeContent: launcher,
        now: new Date(),
        recordApplied: () => {
          throw new Error("must not commit");
        },
        failureInjector: (at) => {
          if (at === checkpoint) throw new Error("injected");
        },
      }),
    ).rejects.toThrow();
    expect(await readFile(resolve(directory, "runtime-v2.mjs"), "utf8")).toBe(legacyRuntime);
    for (const asset of assets(3))
      expect(await readFile(resolve(directory, asset.path))).toEqual(Buffer.from(asset.content));
    expect(await verifyTerminalHookRuntimeArtifact(resolve(directory, "runtime-v2.mjs"))).toBe(
      true,
    );
  },
);
it.each([
  "original_moved:0",
  "published:4",
  "event_recorded",
] as KnowledgeMaterializationCheckpoint[])(
  "recovers interrupted legacy removal at %s",
  async (checkpoint) => {
    const { root, directory } = await legacy();
    const plan = await createTerminalIntegrationPlan(root, launcher);
    let recorded = false;
    await expect(
      applyTerminalIntegrationPlan({
        plan,
        runtimeContent: launcher,
        now: new Date(),
        recordApplied: () => {
          recorded = true;
        },
        failureInjector: (at) => (at === checkpoint ? "interrupt" : undefined),
      }),
    ).rejects.toMatchObject({ code: "knowledge_recovery_required" });
    const result = await recoverKnowledgeMaterialization({
      repositoryRoot: root,
      eventRecorded: () => recorded,
    });
    expect(result.disposition).toBe(recorded ? "committed_cleanup" : "rolled_back");
    expect(await readFile(resolve(directory, "runtime-v2.mjs"), "utf8")).toBe(
      recorded ? launcher : legacyRuntime,
    );
    for (const asset of assets(3)) {
      if (recorded)
        await expect(readFile(resolve(directory, asset.path))).rejects.toMatchObject({
          code: "ENOENT",
        });
      else
        expect(await readFile(resolve(directory, asset.path))).toEqual(Buffer.from(asset.content));
    }
  },
);
it("binds removal to exact native bytes and rejects a stale migration plan", async () => {
  const { root, directory } = await legacy();
  const plan = await createTerminalIntegrationPlan(root, launcher);
  const file = resolve(directory, "native/cas-io.json");
  const value = JSON.parse(await readFile(file, "utf8"));
  value.sourceHash = sha256("changed source");
  await writeFile(file, JSON.stringify(value));
  await expect(
    applyTerminalIntegrationPlan({
      plan,
      runtimeContent: launcher,
      now: new Date(),
      recordApplied: () => undefined,
    }),
  ).rejects.toMatchObject({ code: "knowledge_plan_stale" });
});
