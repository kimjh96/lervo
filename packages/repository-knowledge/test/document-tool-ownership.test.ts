import { execFile } from "node:child_process";
import { mkdir, mkdtemp, rm, writeFile } from "node:fs/promises";
import { tmpdir } from "node:os";
import { dirname, resolve } from "node:path";
import { promisify } from "node:util";

import { applyInitPlan, createInitPlan } from "@lervo/project";
import { afterEach, describe, expect, it } from "vitest";

import {
  documentToolOwnership,
  hasGeneratedFileMarker,
  isAutomationCommitIdentity,
  releasePleaseChangelogPaths,
} from "../src/document-tool-ownership.js";
import { observeToolGeneratedDocuments } from "../src/document-tool-ownership-observation.js";
import {
  inspectConfiguredDocumentNormalization,
  observeDocumentFreshnessFindings,
} from "../src/index.js";

const execute = promisify(execFile);
const roots: string[] = [];

afterEach(async () => {
  await Promise.all(roots.splice(0).map((root) => rm(root, { recursive: true, force: true })));
});

const person = { name: "Developer", email: "dev@example.com" };
const releaseBot = {
  name: "github-actions[bot]",
  email: "41898282+github-actions[bot]@users.noreply.github.com",
};

async function git(root: string, args: string[], identity = person): Promise<string> {
  const { stdout } = await execute("git", ["-C", root, ...args], {
    env: {
      ...process.env,
      GIT_AUTHOR_NAME: identity.name,
      GIT_AUTHOR_EMAIL: identity.email,
      GIT_COMMITTER_NAME: identity.name,
      GIT_COMMITTER_EMAIL: identity.email,
    },
  });
  return stdout;
}

async function write(root: string, path: string, content: string): Promise<void> {
  await mkdir(dirname(resolve(root, path)), { recursive: true });
  await writeFile(resolve(root, path), content);
}

async function commit(root: string, path: string, content: string, identity = person) {
  await write(root, path, content);
  await git(root, ["add", "--", path], identity);
  await git(root, ["commit", "--quiet", "-m", `docs: update ${path}`], identity);
}

async function repository(): Promise<string> {
  const root = await mkdtemp(resolve(tmpdir(), "lervo-tool-ownership-"));
  roots.push(root);
  await execute("git", ["init", "--quiet", "-b", "main", root]);
  return root;
}

const changelog =
  "# Changelog\n\n## [1.2.0](https://example.invalid) (2026-10-01)\n\n* add a thing\n";

describe("tool-generated document evidence", () => {
  it("reads the changelog paths release-please declares, honoring per-package overrides", () => {
    expect(
      releasePleaseChangelogPaths({
        configuration: {
          packages: {
            "apps/app": {},
            "apps/site": { "changelog-path": "docs/CHANGES.md" },
            "packages/quiet": { "skip-changelog": true },
            ".": {},
          },
        },
        manifest: { "apps/app": "1.2.0", "apps/web-next": "0.4.0" },
      }),
    ).toEqual([
      "CHANGELOG.md",
      "apps/app/CHANGELOG.md",
      "apps/site/docs/CHANGES.md",
      "apps/web-next/CHANGELOG.md",
    ]);
    expect(releasePleaseChangelogPaths({ configuration: null, manifest: {} })).toEqual([]);
    expect(
      releasePleaseChangelogPaths({
        configuration: { packages: { "../outside": {} } },
        manifest: null,
      }),
    ).toEqual([]);
  });

  it("recognizes conventional generated markers but not Lervo's own markers or prose", () => {
    expect(hasGeneratedFileMarker("<!-- @generated -->\n# API\n")).toBe(true);
    expect(hasGeneratedFileMarker("// Code generated by protoc-gen-doc. DO NOT EDIT.\n")).toBe(
      true,
    );
    expect(hasGeneratedFileMarker("<!-- lervo:generated repository-entrypoint-v1 -->\n")).toBe(
      false,
    );
    expect(hasGeneratedFileMarker("# Notes\n\nThis page explains generated code.\n")).toBe(false);
    expect(hasGeneratedFileMarker("1\n2\n3\n4\n5\n<!-- @generated -->\n")).toBe(false);
  });

  it("treats GitHub App and bot accounts as automation identities", () => {
    expect(isAutomationCommitIdentity(releaseBot)).toBe(true);
    expect(
      isAutomationCommitIdentity({
        name: "Release Bot",
        email: "release-please[bot]@users.noreply.github.com",
      }),
    ).toBe(true);
    expect(isAutomationCommitIdentity(person)).toBe(false);
    expect(isAutomationCommitIdentity({ name: "botanist", email: "bot@example.com" })).toBe(false);
  });

  it("needs every observed non-Lervo commit to be automation before history proves ownership", () => {
    const base = {
      path: "CHANGELOG.md",
      roles: [],
      generatorOutputs: new Map(),
      generatedAttribute: false,
      leadingContent: "# Changelog\n",
    };
    expect(documentToolOwnership({ ...base, history: [releaseBot, releaseBot] })).toEqual([
      { kind: "tool_commit_history", commitCount: 2 },
    ]);
    expect(documentToolOwnership({ ...base, history: [releaseBot, person] })).toEqual([]);
    expect(documentToolOwnership({ ...base, history: [] })).toEqual([]);
  });

  it("honors a layout role that declares a document tool-generated", () => {
    expect(
      documentToolOwnership({
        path: "packages/core/CHANGES.md",
        roles: [
          {
            roleId: "package_changes",
            path: "CHANGES.md",
            cardinality: "one_per_package",
            lifecycleOwner: "tool_generated",
          },
        ],
        generatorOutputs: new Map(),
        generatedAttribute: false,
        leadingContent: null,
        history: [],
      }),
    ).toEqual([{ kind: "layout_role", roleId: "package_changes" }]);
  });

  it("observes configuration, attributes, markers, and history in a repository", async () => {
    const root = await repository();
    await commit(
      root,
      "release-please-config.json",
      JSON.stringify({ packages: { "apps/app": {} } }),
    );
    await commit(root, ".release-please-manifest.json", JSON.stringify({ "apps/app": "1.2.0" }));
    await commit(root, "apps/app/CHANGELOG.md", changelog);
    await commit(root, ".gitattributes", "docs/api/** linguist-generated\n");
    await commit(root, "docs/api/index.md", "# API\n");
    await commit(root, "docs/schema.md", "<!-- @generated -->\n# Schema\n");
    await commit(root, "packages/lib/CHANGELOG.md", changelog, releaseBot);
    await commit(root, "packages/lib/CHANGELOG.md", `${changelog}\n* more\n`, releaseBot);
    await commit(root, "README.md", "# Project\n", releaseBot);
    await commit(root, "README.md", "# Project\n\nWritten by a person.\n");
    await commit(root, "docs/guide.md", "# Guide\n");

    const owned = await observeToolGeneratedDocuments({
      repositoryRoot: root,
      paths: [
        "apps/app/CHANGELOG.md",
        "docs/api/index.md",
        "docs/schema.md",
        "packages/lib/CHANGELOG.md",
        "README.md",
        "docs/guide.md",
      ],
      roles: [],
    });
    expect(Object.fromEntries(owned)).toEqual({
      "apps/app/CHANGELOG.md": [
        {
          kind: "generator_configuration",
          generator: "release_please",
          configurationPath: "release-please-config.json",
        },
      ],
      "docs/api/index.md": [{ kind: "repository_attribute", attribute: "linguist-generated" }],
      "docs/schema.md": [{ kind: "generated_marker" }],
      "packages/lib/CHANGELOG.md": [{ kind: "tool_commit_history", commitCount: 2 }],
    });
  });

  it("treats a directory outside Git as evidence-free, even when Git closes its input early", async () => {
    const root = await mkdtemp(resolve(tmpdir(), "lervo-tool-ownership-outside-git-"));
    roots.push(root);
    const paths = Array.from({ length: 4096 }, (_, index) => `docs/page-${index}.md`);
    expect(await observeToolGeneratedDocuments({ repositoryRoot: root, paths, roles: [] })).toEqual(
      new Map(),
    );
  });

  it("never offers a tool-generated document for normalization", async () => {
    const root = await mkdtemp(resolve(tmpdir(), "lervo-tool-ownership-normalization-"));
    roots.push(root);
    await applyInitPlan(
      await createInitPlan({
        root,
        projectId: "prj_tool_ownership",
        now: new Date("2026-10-06T00:00:00.000Z"),
      }),
    );
    await write(
      root,
      "release-please-config.json",
      JSON.stringify({ packages: { "apps/app": {} } }),
    );
    await write(root, "apps/app/CHANGELOG.md", changelog);
    await write(root, "apps/app/guide.md", "# Guide\n\nHow to run the app.\n");

    const inspection = await inspectConfiguredDocumentNormalization({ repositoryRoot: root });
    expect(inspection.pendingDocuments).toContain("apps/app/guide.md");
    expect(inspection.pendingDocuments).not.toContain("apps/app/CHANGELOG.md");
  });

  it("never proposes a freshness refresh for a tool-generated document", async () => {
    const root = await mkdtemp(resolve(tmpdir(), "lervo-tool-ownership-freshness-"));
    roots.push(root);
    await execute("git", ["init", "--quiet", "-b", "main", root]);
    await applyInitPlan(
      await createInitPlan({
        root,
        projectId: "prj_tool_ownership_freshness",
        now: new Date("2026-10-06T00:00:00.000Z"),
      }),
    );
    await write(
      root,
      "release-please-config.json",
      JSON.stringify({ packages: { "apps/app": {} } }),
    );
    await write(root, "apps/app/CHANGELOG.md", `${changelog}\nSee [notes](missing-notes.md).\n`);
    await write(root, "apps/app/guide.md", "# Guide\n\nSee [notes](missing-notes.md).\n");
    await git(root, ["add", "-A"]);
    await git(root, ["commit", "--quiet", "-m", "chore: seed"]);

    const observation = await observeDocumentFreshnessFindings({
      repositoryRoot: root,
      now: new Date("2026-10-06T00:00:00.000Z"),
    });
    const paths = observation.findings.map((finding) => finding.documentPath);
    expect(paths).toContain("apps/app/guide.md");
    expect(paths).not.toContain("apps/app/CHANGELOG.md");
  });
});
